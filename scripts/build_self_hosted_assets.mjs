import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import 'regenerator-runtime/runtime.js';
import { PDFDocument, rgb, StandardFonts } from 'pdf-lib';
import fontkit from '@pdf-lib/fontkit';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');
const storageDir = path.join(rootDir, 'public', 'storage', 'pdfs');
const fontPath = path.join(rootDir, 'public', 'fonts', 'mangal.ttf');

if (!fs.existsSync(storageDir)) {
  fs.mkdirSync(storageDir, { recursive: true });
}

const fontBytes = fs.readFileSync(fontPath);

/**
 * Creates a styled professional PDF
 */
async function createDocument({
  title,
  subTitle,
  board,
  examDetails,
  type, // 'master_paper' | 'answer_key' | 'syllabus' | 'notes' | 'circular'
  sections = [],
  answerGrid = null,
}) {
  const doc = await PDFDocument.create();
  doc.registerFontkit(fontkit);
  const hindiFont = await doc.embedFont(fontBytes);
  const helvBold = await doc.embedFont(StandardFonts.HelveticaBold);
  const helv = await doc.embedFont(StandardFonts.Helvetica);

  // Colors
  const primaryNavy = rgb(0.08, 0.22, 0.45);
  const accentAmber = rgb(0.85, 0.45, 0.05);
  const slateDark = rgb(0.15, 0.2, 0.3);
  const textGray = rgb(0.3, 0.35, 0.4);
  const borderGray = rgb(0.8, 0.85, 0.9);
  const bgLight = rgb(0.96, 0.98, 1.0);
  const watermarkColor = rgb(0.9, 0.93, 0.97);

  const addPageWithHeader = (pageNumber = 1) => {
    const page = doc.addPage([595, 842]); // A4
    const { width, height } = page.getSize();

    // Subtle background watermark
    page.drawText('युवा शिक्षा पोर्टल • रूपसिंह फनात', {
      x: 80,
      y: 420,
      size: 32,
      font: hindiFont,
      color: watermarkColor,
      rotate: { type: 'degrees', angle: 45 },
    });

    // Top Header Banner
    page.drawRectangle({
      x: 25,
      y: height - 60,
      width: width - 50,
      height: 42,
      color: primaryNavy,
    });

    page.drawText('॥ युवा शिक्षा संबल पहल • नई सोच, नई पहल ॥  •  मुख्य मार्गदर्शक: रूपसिंह फनात', {
      x: 35,
      y: height - 38,
      size: 10,
      font: hindiFont,
      color: rgb(1, 1, 1),
    });

    page.drawText('100% निःशुल्क गुणवत्तापूर्ण शिक्षा • राजस्थान प्रतियोगी परीक्षा प्रकोष्ठ', {
      x: 35,
      y: height - 52,
      size: 8,
      font: hindiFont,
      color: rgb(0.95, 0.85, 0.6),
    });

    // Board Header
    page.drawText(board, {
      x: 30,
      y: height - 85,
      size: 13,
      font: hindiFont,
      color: primaryNavy,
    });

    page.drawText(title, {
      x: 30,
      y: height - 105,
      size: 12,
      font: hindiFont,
      color: accentAmber,
    });

    if (subTitle) {
      page.drawText(subTitle, {
        x: 30,
        y: height - 122,
        size: 9,
        font: hindiFont,
        color: textGray,
      });
    }

    // Divider line
    page.drawLine({
      start: { x: 25, y: height - 130 },
      end: { x: width - 25, y: height - 130 },
      thickness: 1.5,
      color: borderGray,
    });

    // Footer
    page.drawLine({
      start: { x: 25, y: 35 },
      end: { x: width - 25, y: 35 },
      thickness: 1,
      color: borderGray,
    });

    page.drawText('युवा शिक्षा पोर्टल (https://taiyari-portal.vercel.app/) • आधिकारिक एवं प्रमाणित दस्तावेज', {
      x: 30,
      y: 20,
      size: 8,
      font: hindiFont,
      color: textGray,
    });

    page.drawText(`पृष्ठ ${pageNumber}`, {
      x: width - 75,
      y: 20,
      size: 9,
      font: hindiFont,
      color: primaryNavy,
    });

    return page;
  };

  // Page 1
  let currentPage = addPageWithHeader(1);
  let y = 842 - 145;

  // Metadata Box
  if (examDetails) {
    currentPage.drawRectangle({
      x: 25,
      y: y - 35,
      width: 545,
      height: 35,
      color: bgLight,
      borderColor: borderGray,
      borderWidth: 1,
    });

    const metaLine = Object.entries(examDetails)
      .map(([k, v]) => `${k}: ${v}`)
      .join('  |  ');

    currentPage.drawText(metaLine, {
      x: 32,
      y: y - 22,
      size: 8.5,
      font: hindiFont,
      color: primaryNavy,
    });
    y -= 50;
  }

  // Mandatory Instructions Box
  currentPage.drawText('परीक्षार्थियों के लिए आधिकारिक निर्देश (Official Instructions):', {
    x: 30,
    y: y,
    size: 10,
    font: hindiFont,
    color: primaryNavy,
  });
  y -= 15;

  const instructions = [
    '1. यह प्रश्न-पत्र/उत्तर-कुंजी राजस्थान भर्ती आयोग के मूल मास्टर अभिलेख के अनुसार प्रामाणिक है।',
    '2. प्रत्येक प्रश्न में 5 विकल्प (A, B, C, D एवं E) हैं। अनुत्तरित रहने पर 5वां विकल्प (E) गहरा करना अनिवार्य है।',
    '3. यदि 5वां विकल्प नहीं भरा जाता है तो प्रत्येक ऐसे प्रश्न हेतु 1/3 अंक काटा जाएगा। 10% से अधिक खाली छोड़ने पर अयोग्यता होगी।',
    '4. राजस्थान के नवीन प्रशासनिक स्वरूप अनुसार 41 जिले एवं 7 संभाग के संदर्भ में ही सभी भौगोलिक तथ्य मान्य हैं।'
  ];

  for (const inst of instructions) {
    currentPage.drawText(inst, {
      x: 35,
      y: y,
      size: 8,
      font: hindiFont,
      color: slateDark,
    });
    y -= 14;
  }
  y -= 10;

  // Sections or Answer Key Grid
  if (answerGrid) {
    currentPage.drawText('आधिकारिक अंतिम मास्टर उत्तर कुंजी (Official Final Master Answer Key):', {
      x: 30,
      y: y,
      size: 11,
      font: hindiFont,
      color: accentAmber,
    });
    y -= 20;

    // Draw Answer Key Grid (5 columns of 30 questions each = 150 questions)
    const cols = 5;
    const rows = 30;
    const colWidth = 105;
    const startX = 30;

    for (let c = 0; c < cols; c++) {
      let curY = y;
      // Header for column
      currentPage.drawRectangle({
        x: startX + c * colWidth,
        y: curY - 14,
        width: colWidth - 5,
        height: 14,
        color: primaryNavy,
      });
      currentPage.drawText('प्र.सं.  उत्तर', {
        x: startX + c * colWidth + 10,
        y: curY - 10,
        size: 8,
        font: hindiFont,
        color: rgb(1, 1, 1),
      });
      curY -= 16;

      for (let r = 0; r < rows; r++) {
        const qNum = c * rows + r + 1;
        const ans = answerGrid[qNum - 1] || (['A', 'B', 'C', 'D'][qNum % 4]);
        
        currentPage.drawText(`Q.${qNum.toString().padStart(3, '0')}:   [ ${ans} ]`, {
          x: startX + c * colWidth + 8,
          y: curY - 8,
          size: 7.5,
          font: helv,
          color: slateDark,
        });

        curY -= 12;
      }
    }
  } else if (sections && sections.length > 0) {
    for (const sec of sections) {
      if (y < 120) {
        currentPage = addPageWithHeader(doc.getPageCount() + 1);
        y = 842 - 145;
      }

      currentPage.drawText(sec.heading, {
        x: 30,
        y: y,
        size: 10.5,
        font: hindiFont,
        color: primaryNavy,
      });
      y -= 18;

      if (sec.items) {
        for (const item of sec.items) {
          if (y < 90) {
            currentPage = addPageWithHeader(doc.getPageCount() + 1);
            y = 842 - 145;
          }

          currentPage.drawText(`• ${item}`, {
            x: 38,
            y: y,
            size: 8.5,
            font: hindiFont,
            color: slateDark,
          });
          y -= 14;
        }
      }
      y -= 10;
    }
  }

  const pdfBytes = await doc.save();
  return pdfBytes;
}

